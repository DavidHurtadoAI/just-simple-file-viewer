import { readFile, stat } from 'node:fs/promises';
import assert from 'node:assert/strict';

const pkg = JSON.parse(await readFile('package.json', 'utf8'));
const lock = JSON.parse(await readFile('package-lock.json', 'utf8'));
const manifest = JSON.parse(await readFile('manifest.json', 'utf8'));
const versions = JSON.parse(await readFile('versions.json', 'utf8'));
const meta = JSON.parse(await readFile('build-meta.json', 'utf8'));
assert.equal(pkg.version, manifest.version);
assert.equal(lock.version, manifest.version);
assert.equal(lock.packages[''].version, manifest.version);
assert.equal(versions[manifest.version], manifest.minAppVersion);
assert.match(manifest.id, /^[a-z0-9]+(?:-[a-z0-9]+)*$/);
assert.match(manifest.version, /^\d+\.\d+\.\d+$/);
assert.ok(manifest.description.length <= 250 && manifest.description.endsWith('.'));
assert.equal(Object.keys(pkg.dependencies ?? {}).length, 0);
assert.ok((await readFile('LICENSE', 'utf8')).startsWith('MIT License'));
assert.ok((await readFile('THIRD-PARTY-NOTICES.md', 'utf8')).includes('CodeMirror legacy modes'));
const size = (await stat('main.js')).size;
assert.ok(size < 180 * 1024, `Editor bundle exceeds 180 KiB: ${size}`);
const bundled = Object.keys(meta.inputs);
assert.ok(bundled.some(x => x.includes('legacy-modes')));
assert.ok(!bundled.some(x => /node_modules\/(?:@codemirror\/(?:state|view|commands|search|language)\/|@lezer\/)/.test(x)), 'Host editor libraries must not be bundled');
const js = await readFile('main.js', 'utf8');
assert.ok(!/\b(?:fetch|XMLHttpRequest|eval)\s*\(|https?:\/\//.test(js), 'No networking or dynamic code');
assert.ok(!/\.\s*get(?:Files|MarkdownFiles|AllLoadedFiles)\s*\(/.test(js), 'No vault-wide file enumeration');
const external = [...js.matchAll(/require\(["']([^"']+)["']\)/g)].map(x => x[1]);
const allowed = new Set(['obsidian', '@codemirror/state', '@codemirror/view', '@codemirror/language', '@codemirror/commands', '@codemirror/search', '@lezer/highlight']);
assert.ok(external.length > 0 && external.every(name => allowed.has(name)), 'Only host editor modules may be external');
const readme = await readFile('README.md', 'utf8');
assert.ok(readme.includes('deliberately aims for minimalism'));
assert.ok(readme.includes('releases/latest'));
const releaseWorkflow = await readFile('.github/workflows/release.yml', 'utf8');
const publish = releaseWorkflow.split('\n').find(line => line.trim().startsWith('gh release create '));
assert.ok(publish && /"\$GITHUB_REF_NAME" main\.js manifest\.json styles\.css --verify-tag/.test(publish), 'Release must upload only the three Obsidian assets');
assert.ok(!/\.zip\b/.test(releaseWorkflow), 'No unsupported ZIP release assets');
console.log(`Audit passed: ${(size / 1024).toFixed(1)} KiB; editor libraries supplied by Obsidian; no network calls.`);
